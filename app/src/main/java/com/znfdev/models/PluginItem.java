package com.znfdev.models;

public class PluginItem {
    
    private String name;
    private String main;
    


    public void setName(String name) {
        this.name = name;
    }

    public String getName() {
        return name;
    }

    public void setMain(String main) {
        this.main = main;
    }

    public String getMain() {
        return main;
    }}
